-- StayWise user-owned records. The app applies this migration on the first signed-in visit.
-- Google credentials stay with Google OIDC; this schema stores no passwords.

create table if not exists public.staywise_profiles (
  user_id text primary key,
  email text not null,
  display_name text not null default '',
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table if not exists public.staywise_properties (
  id bigint generated by default as identity primary key,
  owner_id text not null default (auth.jwt() ->> 'sub'),
  name text not null,
  area text not null default '',
  bedrooms integer not null default 2,
  capacity integer not null default 4,
  latitude double precision not null default 38.719,
  longitude double precision not null default -9.165,
  airbnb_url text not null default '',
  booking_url text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.staywise_reservations (
  id bigint generated by default as identity primary key,
  owner_id text not null default (auth.jwt() ->> 'sub'),
  property_id bigint not null references public.staywise_properties(id) on delete cascade,
  guest_name text not null,
  email text not null default '',
  phone text not null default '',
  checkin date not null,
  checkout date not null,
  guests integer not null,
  nightly_rate numeric(12,2) not null,
  status text not null default 'confirmed',
  source text not null default 'Direct',
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.staywise_blocked_dates (
  id bigint generated by default as identity primary key,
  owner_id text not null default (auth.jwt() ->> 'sub'),
  property_id bigint not null references public.staywise_properties(id) on delete cascade,
  start_date date not null,
  end_date date not null,
  reason text not null default ''
);

create table if not exists public.staywise_comparables (
  id bigint generated by default as identity primary key,
  owner_id text not null default (auth.jwt() ->> 'sub'),
  property_id bigint not null references public.staywise_properties(id) on delete cascade,
  name text not null,
  area text not null default '',
  bedrooms integer not null default 1,
  capacity integer not null default 1,
  distance_km double precision not null default 0,
  nightly_rate numeric(12,2) not null,
  observed_date date not null,
  url text not null default '',
  notes text not null default '',
  selected boolean not null default true,
  latitude double precision,
  longitude double precision
);

create table if not exists public.staywise_settings (
  owner_id text not null default (auth.jwt() ->> 'sub'),
  key text not null,
  value text not null,
  primary key (owner_id, key)
);

create table if not exists public.staywise_monthly_assumptions (
  owner_id text not null default (auth.jwt() ->> 'sub'),
  month integer not null check (month between 1 and 12),
  occupancy_percent double precision not null,
  nightly_rate numeric(12,2) not null,
  primary key (owner_id, month)
);

do $$
declare
  table_name text;
  check_expression text;
begin
  foreach table_name in array array[
    'staywise_profiles', 'staywise_properties', 'staywise_reservations', 'staywise_blocked_dates',
    'staywise_comparables', 'staywise_settings', 'staywise_monthly_assumptions'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('grant select, insert, update, delete on public.%I to authenticated', table_name);
    execute format('drop policy if exists %I on public.%I', table_name || '_owner_access', table_name);
    if table_name = 'staywise_profiles' then
      execute 'grant select, insert, update, delete on public.staywise_profiles to authenticated';
      execute 'create policy staywise_profiles_owner_access on public.staywise_profiles for all to authenticated using ((select auth.jwt() ->> ''sub'') = user_id) with check ((select auth.jwt() ->> ''sub'') = user_id)';
    elsif table_name in ('staywise_reservations', 'staywise_blocked_dates', 'staywise_comparables') then
      check_expression := '(select auth.jwt() ->> ''sub'') = owner_id AND EXISTS (SELECT 1 FROM public.staywise_properties p WHERE p.id = property_id)';
    else
      check_expression := '(select auth.jwt() ->> ''sub'') = owner_id';
    end if;
    if table_name = 'staywise_profiles' then
      continue;
    end if;
    execute format(
      'create policy %I on public.%I for all to authenticated using ((select auth.jwt() ->> ''sub'') = owner_id) with check (%s)',
      table_name || '_owner_access', table_name, check_expression
    );
  end loop;
end $$;

grant usage, select on sequence
  public.staywise_properties_id_seq,
  public.staywise_reservations_id_seq,
  public.staywise_blocked_dates_id_seq,
  public.staywise_comparables_id_seq
to authenticated;
